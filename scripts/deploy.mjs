// Deploys PayPerTask to Celo mainnet and records the address.
// Usage: node scripts/deploy.mjs
// Reads the deployer key from deployer.key (never printed, never committed).
import { ethers } from "ethers";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const RPC = "https://forno.celo.org";
const EXPLORER = "https://celoscan.io";

const key = fs.readFileSync(path.join(ROOT, "deployer.key"), "utf8").trim();
const provider = new ethers.JsonRpcProvider(RPC);
const deployer = new ethers.Wallet(key, provider);

const artifact = JSON.parse(
  fs.readFileSync(path.join(ROOT, "artifacts/contracts/PayPerTask.sol/PayPerTask.json"), "utf8")
);

const balance = await provider.getBalance(deployer.address);
console.log("Deployer:", deployer.address);
console.log("Balance:", ethers.formatEther(balance), "CELO");
console.log("Chain ID:", (await provider.getNetwork()).chainId);

const factory = new ethers.ContractFactory(artifact.abi, artifact.bytecode, deployer);
const contract = await factory.deploy();
console.log("Deploy tx:", contract.deploymentTransaction().hash);
console.log("Explorer:", `${EXPLORER}/tx/${contract.deploymentTransaction().hash}`);
await contract.waitForDeployment();
const address = await contract.getAddress();
const receipt = await provider.getTransactionReceipt(contract.deploymentTransaction().hash);
const gasPrice = receipt.gasPrice ?? 0n; // effective gas price (EIP-1559 txs have no tx.gasPrice)
console.log("Deployed at:", address);
console.log("Explorer:", `${EXPLORER}/address/${address}`);
console.log("Gas used:", receipt.gasUsed.toString(), "| cost:", ethers.formatEther(receipt.gasUsed * gasPrice), "CELO");

fs.mkdirSync(path.join(ROOT, "deployments"), { recursive: true });
fs.writeFileSync(
  path.join(ROOT, "deployments/celo.json"),
  JSON.stringify(
    {
      network: "celo",
      chainId: 42220,
      contract: "PayPerTask",
      address,
      deployTx: contract.deploymentTransaction().hash,
      deployer: deployer.address,
      deployedAt: new Date().toISOString(),
    },
    null,
    2
  )
);
// Frontend config (public address only).
fs.writeFileSync(
  path.join(ROOT, "frontend/config.js"),
  `// Generated by scripts/deploy.mjs — public contract address only.\nwindow.PAYPERTASK_CONFIG = {\n  chainId: 42220,\n  rpc: "https://forno.celo.org",\n  explorer: "https://celoscan.io",\n  address: "${address}",\n};\n`
);
console.log("Saved deployments/celo.json and frontend/config.js");
